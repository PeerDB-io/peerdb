#!/usr/bin/env python3
"""Unit test driver — port of flow.yml's `unit_tests` job (no services).

Runs the flow and flow/pkg unit suites under gotestsum (JUnit output) via
praktika's native Result.from_junit_run, which runs the command and translates
the JUnit report into a structured Result whose sub-results are the individual
test cases (failures first), instead of a bare pass/fail from the shell exit
code. The JUnit XML is attached to each sub-result, so the raw reports are
available as artifacts too.

Protos are generated by the job's pre-hook; the Go toolchain + gotestsum are
baked into the runner image (ci/infrastructure/projects.py).
"""
import os
import shutil
import sys

# Make praktika importable from the repo root.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.getcwd())

from praktika.result import Result  # noqa: E402
from praktika.utils import Utils  # noqa: E402

FLOW_JUNIT = "logs/unit-test-results.xml"
PKG_JUNIT = "logs/unit-pkg-test-results.xml"


def main():
    sw = Utils.Stopwatch()
    os.makedirs("logs", exist_ok=True)
    # The tests autoload .env (godotenv); it is gitignored, so seed the template.
    if not os.path.exists(".env"):
        shutil.copyfile(".env.example", ".env")

    # Absolute paths: from_junit_run anchors a relative report_glob to workdir,
    # which would miss the repo-root logs/ dir these commands write to.
    flow_junit = os.path.abspath(FLOW_JUNIT)
    pkg_junit = os.path.abspath(PKG_JUNIT)

    flow = Result.from_junit_run(
        command="gotestsum --format standard-quiet --no-color "
        f"--junitfile {flow_junit} -- -p 32 ./... -timeout 600s",
        report_glob=flow_junit,
        name="flow unit tests",
        workdir="flow",
    )
    pkg = Result.from_junit_run(
        command="gotestsum --format standard-quiet --no-color "
        f"--junitfile {pkg_junit} -- -p 32 ./... -timeout 300s",
        report_glob=pkg_junit,
        name="flow/pkg unit tests",
        workdir="flow/pkg",
    )

    # name/status omitted: create_from defaults name to JOB_NAME so the runner's
    # Result.from_fs(job.name) finds this file, and derives status by aggregating
    # the sub-results (any FAIL/ERROR -> job fails). complete_job writes the
    # result file and exits with the matching code.
    Result.create_from(results=[flow, pkg], stopwatch=sw).complete_job()


if __name__ == "__main__":
    main()
