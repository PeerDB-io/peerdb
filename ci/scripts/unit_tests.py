#!/usr/bin/env python3
"""Unit test driver — port of flow.yml's `unit_tests` job (no services).

Runs the flow and flow/pkg unit suites under gotestsum (JUnit output), then
translates the JUnit reports into a structured praktika Result (via
junit_result) so the report page shows a per-test table (failures first)
instead of a bare pass/fail from the shell exit code. The JUnit XML is attached
to each sub-result, so the raw reports are available as artifacts too.

Protos are generated by the job's pre-hook; the Go toolchain + gotestsum are
baked into the runner image (ci/infrastructure/projects.py).
"""
import os
import shutil
import subprocess
import sys

# Import the sibling translator and make praktika importable from the repo root.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.getcwd())

from praktika.result import Result  # noqa: E402
from praktika.utils import Utils  # noqa: E402

from junit_result import build_job_result  # noqa: E402

FLOW_JUNIT = "logs/unit-test-results.xml"
PKG_JUNIT = "logs/unit-pkg-test-results.xml"


def _run(cmd, cwd=None):
    print(f"+ ({cwd or '.'}) {cmd}", flush=True)
    return subprocess.run(cmd, shell=True, cwd=cwd).returncode


def main():
    sw = Utils.Stopwatch()
    os.makedirs("logs", exist_ok=True)
    # The tests autoload .env (godotenv); it is gitignored, so seed the template.
    if not os.path.exists(".env"):
        shutil.copyfile(".env.example", ".env")

    sw_flow = Utils.Stopwatch()
    rc_flow = _run(
        "gotestsum --format standard-quiet --no-color "
        f"--junitfile ../{FLOW_JUNIT} -- -p 32 ./... -timeout 600s",
        cwd="flow",
    )
    flow = build_job_result(FLOW_JUNIT, rc_flow, sw_flow, name="flow unit tests")

    sw_pkg = Utils.Stopwatch()
    rc_pkg = _run(
        "gotestsum --format standard-quiet --no-color "
        f"--junitfile ../../{PKG_JUNIT} -- -p 32 ./... -timeout 300s",
        cwd="flow/pkg",
    )
    pkg = build_job_result(PKG_JUNIT, rc_pkg, sw_pkg, name="flow/pkg unit tests")

    # name/status omitted: create_from defaults name to JOB_NAME so the runner's
    # Result.from_fs(job.name) finds this file, and derives status by aggregating
    # the sub-results (any FAIL/ERROR -> job fails). complete_job writes the
    # result file and exits with the matching code.
    Result.create_from(results=[flow, pkg], stopwatch=sw).complete_job()


if __name__ == "__main__":
    main()
