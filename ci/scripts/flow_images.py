#!/usr/bin/env python3
"""Build the flow images once and publish them as a Praktika artifact.

Port of flow.yml's `flow_images` job. Builds flow-api / flow-worker /
flow-snapshot-worker with stacks/build-flow-images.sh (the same script the
Tiltfile's custom_build runs), then `docker save | zstd` into
flow-images.tar.zst. The workflow declares that file as an S3 artifact
(provides=["flow-images"]); the matrix flow-test jobs require it and
ci/scripts/flow_test.py loads it (docker load) and sets
PEERDB_CI_PREBUILT_FLOW_IMAGES=1 so Tilt skips the per-job image builds.

Protos are generated by the job's pre-hook (the images embed flow/generated).
"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.getcwd())

from praktika.result import Result  # noqa: E402
from praktika.utils import Utils  # noqa: E402

IMAGES = ["flow-api", "flow-worker", "flow-snapshot-worker"]
ARCHIVE = "flow-images.tar.zst"


def _run(cmd):
    print(f"+ {cmd}", flush=True)
    return subprocess.run(cmd, shell=True).returncode


def main():
    sw = Utils.Stopwatch()
    results = []

    all_built = True
    for image in IMAGES:
        sw_i = Utils.Stopwatch()
        rc = _run(f"stacks/build-flow-images.sh {image}")
        results.append(
            Result.create_from(
                name=f"build {image}",
                status=Result.Status.OK if rc == 0 else Result.Status.FAIL,
                stopwatch=sw_i,
            )
        )
        all_built = all_built and rc == 0

    # Only save if every image built, otherwise the artifact would be partial
    # and the consumers would docker-load a broken set.
    if all_built:
        sw_s = Utils.Stopwatch()
        rc = _run(f"docker save {' '.join(IMAGES)} | zstd -T0 -3 > {ARCHIVE}")
        _run(f"ls -lh {ARCHIVE} || true")
        results.append(
            Result.create_from(
                name="docker save + zstd",
                status=Result.Status.OK if rc == 0 else Result.Status.FAIL,
                stopwatch=sw_s,
            )
        )

    Result.create_from(results=results, stopwatch=sw).complete_job()


if __name__ == "__main__":
    main()
