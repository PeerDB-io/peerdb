#!/usr/bin/env python3
"""Driver for flow.yml's `test_selection_coverage` guard.

Runs .github/scripts/check-flow-test-selection.sh — which asserts every matrix
target has a source job and every tilt-tagged test package is owned by exactly
one source job in flow.yml — and emits a structured praktika Result instead of a
bare exit-code pass/fail. This is a consistency gate (not a test suite), so it's
one leaf Result that carries the script's output on failure.

Protos are generated by the job's pre-hook; Go/yq are baked into the runner
image (ci/infrastructure/projects.py).
"""
import os
import subprocess
import sys

sys.path.insert(0, os.getcwd())  # make praktika importable from the repo root

from praktika.result import Result  # noqa: E402
from praktika.utils import Utils  # noqa: E402

SCRIPT = ".github/scripts/check-flow-test-selection.sh"


def main():
    sw = Utils.Stopwatch()
    print(f"+ bash {SCRIPT}", flush=True)
    proc = subprocess.run(["bash", SCRIPT], text=True, capture_output=True)
    output = (proc.stdout or "") + (proc.stderr or "")
    if output:
        print(output, end="", flush=True)

    ok = proc.returncode == 0
    # name/status default: create_from uses JOB_NAME so the runner's
    # Result.from_fs(job.name) finds this file. complete_job writes the result
    # and exits with the matching code.
    Result.create_from(
        status=Result.Status.OK if ok else Result.Status.FAIL,
        stopwatch=sw,
        info="" if ok else (output.strip() or f"check exited {proc.returncode}"),
    ).complete_job()


if __name__ == "__main__":
    main()
