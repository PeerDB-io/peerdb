#!/usr/bin/env python3
"""Compile every flow test package once and publish GOCACHE as a Praktika artifact.

Port of flow.yml's `go_build_cache` job. Without it the flow-test matrix
recompiles the same packages in each of its permutations; this job compiles them
once (via .github/scripts/select-flow-tests.sh over ./..., the SAME script,
build tags and cover flags the matrix uses) and ships the resulting Go build
cache so each matrix job restores it instead of compiling from scratch.

The workflow declares go-build-cache.tar.zst as an S3 artifact
(provides=["go-build-cache"]); ci/scripts/flow_test.py restores it into
`go env GOCACHE` before selecting/running tests (the consumer side, mirroring
tilt-flow.yml's "Fetch prebuilt Go build cache" step).

Praktika has no actions/cache-style restore; the artifact IS the cache. We ship
the whole GOCACHE (not GHA's setup-go diff) because a fresh runner has nothing
warm to layer on. The modules are restored by the job's `go_cache.py restore mod`
pre_hook, so the `go mod download` below is a fast no-op on a warm module cache.
Protos are generated by the job's pre-hook; listing/compiling tests needs no
services.
"""
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.getcwd())

from praktika.result import Result  # noqa: E402
from praktika.utils import Utils  # noqa: E402

import go_cache  # noqa: E402

ARCHIVE = go_cache.ARCHIVES["build"]


def _run(cmd, **kwargs):
    print(f"+ {cmd if isinstance(cmd, str) else ' '.join(cmd)}", flush=True)
    return subprocess.run(cmd, shell=isinstance(cmd, str), **kwargs).returncode


def _ok(rc):
    return Result.Status.OK if rc == 0 else Result.Status.FAIL


def main():
    sw = Utils.Stopwatch()
    results = []

    runner_temp = os.environ.get("RUNNER_TEMP") or tempfile.mkdtemp()
    os.environ["RUNNER_TEMP"] = runner_temp
    os.makedirs(runner_temp, exist_ok=True)

    # Same package patterns / tags / cover flags the matrix runs, so the entries
    # produced here are exactly the ones its Select tests + Run tests steps look
    # up. ./... over both the flow and flow/pkg modules.
    env = os.environ.copy()
    env["TEST_PACKAGES"] = "./..."
    env["PKG_TEST_PACKAGES"] = "./..."
    # Match the flow matrix's coverage setting so the cache we ship has the exact
    # objects it will restore. Coverage is off by default (flow_test.py), so the
    # producer compiles uninstrumented too; flip both together to re-enable.
    env["FLOW_COVERAGE"] = os.environ.get("FLOW_COVERAGE", "0")

    sw_mod = Utils.Stopwatch()
    rc = _run("go mod download", cwd="flow", env=env)
    rc = _run("go mod download", cwd="flow/pkg", env=env) or rc
    results.append(Result.create_from(
        name="go mod download", status=_ok(rc), stopwatch=sw_mod,
    ))

    sw_c = Utils.Stopwatch()
    rc_compile = _run(["bash", ".github/scripts/select-flow-tests.sh"], env=env)
    results.append(Result.create_from(
        name="compile all flow tests", status=_ok(rc_compile), stopwatch=sw_c,
    ))

    # Only publish if the compile succeeded, otherwise the artifact would be an
    # incomplete cache and consumers would recompile the gaps anyway.
    if rc_compile == 0:
        sw_p = Utils.Stopwatch()
        rc_pack = go_cache.pack("build", ARCHIVE)
        results.append(Result.create_from(
            name="pack GOCACHE", status=_ok(rc_pack), stopwatch=sw_p,
        ))

    Result.create_from(results=results, stopwatch=sw).complete_job()


if __name__ == "__main__":
    main()
