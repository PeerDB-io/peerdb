#!/usr/bin/env python3
"""Consolidated lint driver — ports .github/workflows/golang-lint.yml and the
lint half of .github/workflows/ui-lint.yml into one job with multiple steps.

Each step becomes a sub-result in a structured praktika Result (so the report
shows exactly which linter failed), and the job fails if any step fails. Protos
are generated by the job's pre-hook; golangci-lint, Go and Node are baked into
the x86_64 image (ci/infrastructure/projects.py).

Steps:
  - go workspace init (flow + flow/pkg + e2e_cleanup; flow/pkg's ruleguard
    imports flow/generated/protos, so lint needs the workspace)
  - golangci-lint: flow, flow/pkg, e2e_cleanup
  - ui: npm ci, eslint (npm run lint), prettier --check
"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.getcwd())

from praktika.result import Result  # noqa: E402
from praktika.utils import Utils  # noqa: E402

# (name, shell command, cwd)
STEPS = [
    ("go workspace", "go work init ./flow ./flow/pkg ./e2e_cleanup", "."),
    ("golangci-lint flow", "golangci-lint run --timeout=10m", "flow"),
    ("golangci-lint flow/pkg", "golangci-lint run --config=../.golangci.yml --timeout=10m", "flow/pkg"),
    ("golangci-lint e2e_cleanup", "golangci-lint run --timeout=10m", "e2e_cleanup"),
    ("ui npm ci", "npm ci", "ui"),
    ("ui eslint", "npm run lint", "ui"),
    ("ui prettier", 'npx prettier --check "**/*.{js,jsx,ts,tsx,json}"', "ui"),
]


def main():
    sw = Utils.Stopwatch()
    results = []
    for name, cmd, cwd in STEPS:
        sw_step = Utils.Stopwatch()
        print(f"\n=== {name} === ({cwd}) {cmd}", flush=True)
        proc = subprocess.run(cmd, shell=True, cwd=cwd, stderr=subprocess.STDOUT,
                              stdout=subprocess.PIPE, text=True)
        print(proc.stdout, flush=True)
        results.append(
            Result.create_from(
                name=name,
                status=Result.Status.OK if proc.returncode == 0 else Result.Status.FAIL,
                stopwatch=sw_step,
                # Keep the tail of the output on failure for the report.
                info="" if proc.returncode == 0 else "\n".join(proc.stdout.splitlines()[-40:]),
            )
        )
        # go workspace is a prerequisite for the golangci steps; stop early if it
        # fails so the failures are legible.
        if proc.returncode != 0 and name == "go workspace":
            break

    Result.create_from(results=results, stopwatch=sw).complete_job()


if __name__ == "__main__":
    main()
